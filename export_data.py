"""Write data.js (used by index.html) from the SQLite database, so the plan lives in one place."""
import json, sqlite3, sys

db = sqlite3.connect(sys.argv[1] if len(sys.argv) > 1 else "abhyasa.db")
db.row_factory = sqlite3.Row
e = db.execute("SELECT * FROM exams ORDER BY exam_id LIMIT 1").fetchone()
q = lambda sql: db.execute(sql, (e["exam_id"],)).fetchall()

data = {
    "exam": {"name": e["exam_name"], "date": e["exam_date"], "revisionDays": e["revision_days"]},
    "subjects": [{"id": r["subject_id"], "name": r["subject_name"]}
                 for r in q("SELECT * FROM subjects WHERE exam_id=? ORDER BY subject_id")],
    "sources": [{"id": r["source_id"], "sub": r["subject_id"], "name": r["source_name"],
                 "unit": r["unit"], "mpu": r["min_per_unit"]}
                for r in q("SELECT s.* FROM sources s JOIN subjects j USING(subject_id)"
                           " WHERE j.exam_id=? ORDER BY s.source_id")],
    "topics": [{"id": r["topic_id"], "src": r["source_id"], "name": r["topic_name"],
                "units": r["units"], "order": r["topic_order"], "weak": r["weak"]}
               for r in q("SELECT t.* FROM topics t JOIN sources s USING(source_id)"
                          " JOIN subjects j USING(subject_id) WHERE j.exam_id=?"
                          " ORDER BY t.topic_id")],
}
with open("data.js", "w", encoding="utf-8") as f:
    f.write("// Generated by export_data.py from the database. Do not edit by hand.\n")
    f.write("const DATA = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")
print("wrote data.js:", len(data["topics"]), "topics")
